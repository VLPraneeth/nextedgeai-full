    @ChangeSet(order = "001", id = "addSyncariConnector", author = "neelesh")
    public void addConnector(MongoTemplate db) {
    	MongoDatabase syncariDb = MigrationContext.getSyncariDB();
    	MongoCollection<Document> metadata = syncariDb.getCollection("connectorMetadata");
		Document filterDoc = new Document();
	    filterDoc.append("name", Constants.SYNCARI);
		Document connectorMeta = metadata.find(filterDoc).first();
		
        MongoCollection<Document> connectors = db.getCollection("connector");
        Document entity = new Document("name", SYNCARI_CONNECTOR_NAME)
                .append("displayName","Syncari")
                .append("status", ConnectorStatus.ACTIVE.name())
                .append("type", Constants.SYNCARI)
                .append("isSystem", true)
                .append("typeId", connectorMeta.get("_id").toString())
                .append("metadata", connectorMeta)
                .append("seeded", true)
                .append("endpoint", "local");
        connectors.insertOne(entity);

    }

	@ChangeSet(order = "009", id = "updateSyncariConnectorSetMetadataId", author = "abhinav")
	public void updateSyncariConnectorSetMetadataId(MongoTemplate db) {
		MongoCollection<Document> connectors = db.getCollection("connector");
		Document syncariConnector = getSyncariConnector(db);
		Map syncariMetadata = (Map) syncariConnector.get("metadata");
		Bson query = eq("_id", syncariConnector.getObjectId("_id"));
		connectors.findOneAndUpdate(query,
				new Document("$set", new Document("metadataId", syncariMetadata.get("_id").toString()))
						.append("$unset", new Document("typeId", "")));
	}

    private Document getSyncariConnector(MongoTemplate db){
        MongoCollection<Document> connector = db.getCollection("connector");
        Document filterDoc = new Document();
        filterDoc.append("name", SYNCARI_CONNECTOR_NAME);
        return connector.find(filterDoc).first();

    }

    @ChangeSet(order = "002", id = "customerEntitySeed", author = "neelesh")
    public void addEntities(MongoTemplate db) {
        MongoCollection<Document> entities = db.getCollection("entityDefinition");
        Map<String, List<String>> entityMap = Map.of(
        		Constants.SYNCARI, Arrays.asList(
        		        Constants.ACCOUNT.toLowerCase(), 
        		        Constants.CONTACT.toLowerCase(),
        		        Constants.LEAD.toLowerCase(),
        		        Constants.OPPORTUNITY.toLowerCase(),
        		        Constants.TICKET.toLowerCase(), 
        		        Constants.ACTIVITY.toLowerCase(), 
        		        Constants.USER.toLowerCase())
        );
        entityMap.forEach((k , v) -> {
            v.forEach(entityName -> {
                Document syncariConnector = getSyncariConnector(db);
				Document entity = new Document("apiName", entityName)
                        .append("displayName", StringUtils.capitalize(entityName))
                        .append("status", ConnectorStatus.ACTIVE.name())
                        .append("connectorId", syncariConnector.getObjectId("_id").toHexString())
                        .append("connectorTypeId", syncariConnector.get("typeId").toString())
						.append("seeded", true)
                        .append("systemType", k);

                entities.insertOne(entity);
            });
        });
    }

